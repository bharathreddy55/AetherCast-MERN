const crypto = require('crypto');
const User = require('../models/User');
const accessError = (status, message) => Object.assign(new Error(message), { status });
const exactEmail = email => new RegExp(`^${email.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'i');

async function findProfile(subject, email) {
  return await User.findOne({ supabaseUserId: subject })
    || await User.findOne({ email })
    || await User.findOne({ email: exactEmail(email) });
}

function checkProfile(user, subject) {
  if (user?.supabaseUserId && user.supabaseUserId !== subject) {
    throw accessError(403, 'This profile belongs to a different account');
  }
  if (user?.accountStatus === 'suspended') throw accessError(403, 'Your account has been suspended');
  return user;
}

async function adoptProfile(user, subject) {
  checkProfile(user, subject);
  if (user.supabaseUserId) return user;
  // Match all legacy unlinked representations, never a different identity.
  let linked;
  try {
    linked = await User.findOneAndUpdate({ _id: user._id,
      $or: [{ supabaseUserId: { $exists: false } }, { supabaseUserId: null }, { supabaseUserId: '' }] },
    { $set: { supabaseUserId: subject } }, { new: true, runValidators: true, overwriteImmutable: true });
  } catch (error) {
    if (error.code !== 11000) throw error;
    linked = await User.findOne({ supabaseUserId: subject });
    if (!linked) throw error;
  }
  if (!linked) linked = await User.findOne({ supabaseUserId: subject });
  if (!linked) throw accessError(403, 'Unable to link this owner profile');
  return checkProfile(linked, subject);
}

async function resolveOwnerProfile(decoded) {
  const email = decoded.email.trim().toLowerCase();
  const previous = await findProfile(decoded.sub, email);
  if (previous) return adoptProfile(previous, decoded.sub);

  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      // User-editable usernames may already belong to an unrelated profile.
      // New internal names are generated by the server; identity uses the UID.
      return await User.create({
        supabaseUserId: decoded.sub, username: `owner-${crypto.randomBytes(16).toString('hex')}`,
        name: decoded.user_metadata?.full_name || decoded.user_metadata?.name || email.split('@')[0], email,
        password: crypto.randomBytes(32).toString('hex'), role: 'listener',
        bio: decoded.user_metadata?.bio || '', avatar: decoded.user_metadata?.avatar_url || '', isVerified: true,
      });
    } catch (error) {
      if (error.code !== 11000) throw error;
      // Simultaneous first-login requests can both observe a missing profile.
      // Recover by verified UID/email, never by a conflicting username.
      const concurrent = await findProfile(decoded.sub, email);
      if (concurrent) return adoptProfile(concurrent, decoded.sub);
      const fields = Object.keys(error.keyPattern || error.keyValue || {});
      if (fields.length !== 1 || fields[0] !== 'username' || attempt === 2) throw error;
    }
  }
}

module.exports = { resolveOwnerProfile };
